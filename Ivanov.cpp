// virtual_memory_demo.cpp
// Visual Studio 2022, C++17 (или C++20)
// Демонстрация выделения/освобождения виртуальных страниц (4 КБ)
// Сценарий 1: утечка через new[] + delete
// Сценарий 2: корректное совместное владение через shared_ptr<vector<DataBlock>>

#include <iostream>
#include <memory>     // std::shared_ptr, std::make_shared
#include <vector>
#include <string>
#include <locale>

// ============================================================
// DataBlock — модель одной виртуальной страницы
// Массив int[1024] = 1024 * 4 байт = 4096 байт = 4 КБ
// ровно столько, сколько занимает одна стандартная страница в ОС.
// ============================================================
class DataBlock
{
public:
    int  data[1024];   // 4 КБ — «тело» виртуальной страницы
    int  id;           // идентификатор блока (номер страницы)

    explicit DataBlock(int blockId) : id(blockId)
    {
        // Обращаемся ко всем элементам, чтобы страница реально «материализовалась»
        // (иначе ОС может не выделить физический фрейм до первого касания —
        //  это называется demand paging / отложенное выделение).
        for (int i = 0; i < 1024; ++i)
            data[i] = blockId;

        std::cout << "[+] Конструктор: Выделена виртуальная страница для Блока #"
            << id << "\n";
    }

    ~DataBlock()
    {
        std::cout << "[-] Деструктор: ОС освободила страницу Блока #"
            << id << "\n";
    }
};

// ============================================================
// СЦЕНАРИЙ 1. Утечка страниц памяти.
// new[] выделяет массив из 3 объектов — это 3 виртуальные страницы.
// Но освобождаем через обычный delete (а не delete[]).
// Результат: деструктор вызывается только у первого элемента,
// остальные две страницы «утекают» — ОС их не получит до конца процесса.
// ============================================================
void Scenario1_Leak()
{
    std::cout << "\n========== СЦЕНАРИЙ 1: УТЕЧКА СТРАНИЦ ПАМЯТИ ==========\n";
    std::cout << "Выделяем массив из 3 DataBlock через new[]...\n";

    DataBlock* blocks = new DataBlock[3]{ DataBlock(1), DataBlock(2), DataBlock(3) };

    std::cout << "\nОсвобождаем через ОБЫЧНЫЙ delete (ошибка!)...\n";
    // ОШИБКА: должно быть delete[] blocks;
    // Обычный delete вызовет деструктор только для blocks[0].
    // Память же под массив будет возвращена некорректно —
    // это Undefined Behavior, и в MSVC Debug вы, скорее всего,
    // увидите assertion из-за проверок CRT.
    delete blocks;

    std::cout << "\nИтог: деструкторы для #2 и #3 НЕ вызваны — страницы утекли.\n";
    std::cout << "      (ОС не получила уведомления об освобождении этих 4-КБ страниц)\n";
}

// ============================================================
// СЦЕНАРИЙ 2. Правильное совместное владение.
// vector<DataBlock> хранит наши страницы непрерывно, а shared_ptr
// следит за «счётчиком владельцев». Память освобождается ровно тогда,
// когда исчезает последний shared_ptr на вектор.
// ============================================================
void Scenario2_SmartPointers()
{
    std::cout << "\n========== СЦЕНАРИЙ 2: ИСПРАВЛЕНИЕ ЧЕРЕЗ УМНЫЕ УКАЗАТЕЛИ ==========\n";

    // Первый владелец. make_shared сразу создаёт и объект управления, и вектор.
    std::shared_ptr<std::vector<DataBlock>> pointer1 =
        std::make_shared<std::vector<DataBlock>>();

    pointer1->reserve(3);            // заранее под 3 страницы
    pointer1->emplace_back(1);       // страница #1
    pointer1->emplace_back(2);       // страница #2
    pointer1->emplace_back(3);       // страница #3

    std::cout << "Создан pointer1. use_count = " << pointer1.use_count() << "\n";

    // Второй владелец — копия первого. Счётчик ссылок = 2.
    std::shared_ptr<std::vector<DataBlock>> pointer2 = pointer1;
    std::cout << "Скопировали в pointer2. pointer1.use_count = "
        << pointer1.use_count()
        << ", pointer2.use_count = " << pointer2.use_count() << "\n";

    // Отпускаем pointer1. Счётчик падает до 1 — но страницы ЖИВЫ,
    // потому что владельцем остаётся pointer2.
    pointer1.reset();
    std::cout << "pointer1.reset() выполнен. pointer1 = "
        << (pointer1 ? "не пуст" : "пуст")
        << ", pointer2.use_count = " << pointer2.use_count() << "\n";
    std::cout << ">>> Страницы #1..#3 всё ещё живы: ими владеет pointer2.\n";

    std::cout << "\nВыходим из функции — уничтожается последний владелец pointer2...\n";
    // Здесь, при разрушении pointer2, use_count станет 0,
    // и тогда vector<DataBlock>::~vector вызовет деструкторы DataBlock.
}

// ============================================================
int main()
{
    setlocale(LC_ALL, "Russian");

    Scenario1_Leak();
    Scenario2_SmartPointers();

    std::cout << "\n========== ПРОГРАММА ЗАВЕРШЕНА ==========\n";
    return 0;
}